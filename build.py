#!/usr/bin/env python3
"""Render plain HTML from sites.json. No JavaScript is used on the site.

Edit sites.json, run this script, then commit the generated pages.
"""
from __future__ import annotations

import html
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SITE = "https://watch.grokforum.site"
CSP = "default-src 'none'; style-src 'self'; img-src 'self'; base-uri 'none'; form-action 'none'"
BANNER = (
    '<div class="draft" role="note"><p><strong>DRAFT.</strong> This site is an unfinished draft. '
    "Drafts are labelled. "
    '<a href="https://grokforum.site/">Part of grokforum.site</a></p></div>'
)
FOOTER = (
    "<footer><p>GrokForum watch directory (draft) · "
    '<a href="/">Home</a> · '
    '<a href="https://grokforum.site/">Part of grokforum.site</a></p></footer>'
)
def esc(s: str) -> str:
    return html.escape(s, quote=True)


def head(title: str, path: str, description: str) -> str:
    canon = SITE + path
    return f"""<!doctype html>
<html lang="en-ZA">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="description" content="{esc(description)}">
<meta http-equiv="Content-Security-Policy" content="{CSP}">
<meta name="referrer" content="no-referrer">
<meta name="robots" content="noindex, nofollow">
<link rel="icon" href="/favicon.svg" type="image/svg+xml">
<link rel="stylesheet" href="/assets/site.css">
<title>DRAFT · {esc(title)}</title>
<link rel="canonical" href="{esc(canon)}">
</head>
<body>
<a class="skip" href="#main">Skip to content</a>
{BANNER}
"""


def page(title: str, path: str, description: str, body: str) -> str:
    return (
        head(title, path, description)
        + f'<main id="main">\n{body}\n</main>\n'
        + FOOTER
        + "\n</body>\n</html>\n"
    )


def repo_links(repos: list[dict]) -> str:
    if not repos:
        return ""
    parts = []
    for r in repos:
        parts.append(
            f'<a href="{esc(r["url"])}">{esc(r["name"])}</a> '
            f'<span class="kind">{esc(r["kind"])}</span>'
        )
    return '<p class="repos">Repos: ' + " · ".join(parts) + "</p>\n"


def render_index(sites: list[dict], intro: str) -> str:
    items = []
    for s in sites:
        items.append(
            "  <li>\n"
            f'    <h2><a href="{esc(s["url"])}">{esc(s["name"])}</a> '
            f'<span class="badge">{esc(s["status"])}</span></h2>\n'
            f'    <p class="site-url">{esc(s["url"])}</p>\n'
            f'    <p>{esc(s["description"])}</p>\n'
            f'    {repo_links(s.get("repos") or [])}'
            "  </li>"
        )
    body = f"""<!-- generated by build.py from sites.json; do not edit the list by hand -->
<h1>GrokForum watch directory</h1>
<p class="lede">{esc(intro)}</p>
<ul class="sites">
{chr(10).join(items)}
</ul>
"""
    return page(
        "Watch directory",
        "/",
        "This is to keep an eye on things affecting all South Africans.",
        body,
    )


def render_404() -> str:
    body = """<h1>Page not found</h1>
<p>There is no page at this address.</p>
<ul>
<li><a href="/">Go to the home page</a></li>
</ul>
"""
    return page("Page not found", "/404.html", "This address has no watch directory page.", body)


def main() -> None:
    data = json.loads((ROOT / "sites.json").read_text(encoding="utf-8"))
    sites = data["sites"]
    intro = data["intro"]
    (ROOT / "index.html").write_text(render_index(sites, intro), encoding="utf-8")
    (ROOT / "404.html").write_text(render_404(), encoding="utf-8")
    print(f"wrote index.html and 404.html ({len(sites)} sites)")


if __name__ == "__main__":
    main()
